-- Esquema simplificado para o experimento (Lab05).
--
-- Reproduz, para as tabelas dos estudos, as colunas relevantes do Sentinela
-- (nomes e tipos conforme docs/BANCO.md do projeto) mais colunas de enchimento
-- para dar as linhas um tamanho parecido com o real. Nao ha nenhum dado real.
--
-- Estado "sem_indice": somente chaves primarias e a chave estrangeira de
-- vistoria_visitas (o PostgreSQL NAO indexa chaves estrangeiras sozinho, e em
-- producao nao existe indice em vistoria_visitas(vistoria_id), ver PROPOSTA.md 1.2).
-- Os indices dos estudos sao criados e removidos pelo benchmark
-- (indices_v2.sql e indice_vistoria_visitas.sql).
--
-- Fora do escopo, de proposito: indices de tenant (V76), trigram de busca por
-- nome e indices parciais de documento. Existem em producao e nao afetam as
-- consultas medidas aqui (ver ameaca de construto).

DROP TABLE IF EXISTS vistoria_visitas;
DROP TABLE IF EXISTS vistorias;
DROP TABLE IF EXISTS ocorrencias;
DROP TABLE IF EXISTS fichas;

CREATE TABLE ocorrencias (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id        BIGINT       NOT NULL,
    tenant_id         BIGINT       NOT NULL DEFAULT 1,
    data_vandalismo   DATE,
    data_acionamento  DATE,
    hora_acionamento  TIME,
    status            VARCHAR(255),
    fonte             VARCHAR(255),
    bairro            VARCHAR(255),
    cidade            VARCHAR(255),
    rua               VARCHAR(255),
    numero_bo         VARCHAR(255),
    numeroocorrencia  VARCHAR(255),
    observacoes       TEXT
);

CREATE TABLE fichas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id    BIGINT       NOT NULL,
    tenant_id     BIGINT       NOT NULL DEFAULT 1,
    ativo         BOOLEAN      NOT NULL,
    data_criacao  TIMESTAMP    NOT NULL,
    nome          VARCHAR(255) NOT NULL,
    mae           TEXT,
    descricao     TEXT,
    perfil        TEXT,
    foto_url      TEXT,
    observacoes   TEXT,
    dados_extras  TEXT
);

-- Em producao a linha de fichas e larga (cerca de 3,4 kB de largura media estimada),
-- mas o heap tem so cerca de 330 paginas para 8.010 linhas (cerca de 340 bytes por
-- linha): o resto fica fora da linha (TOAST). `dados_extras` reproduz isso: texto grande
-- armazenado fora da linha e sem compressao.
ALTER TABLE fichas ALTER COLUMN dados_extras SET STORAGE EXTERNAL;

CREATE TABLE vistorias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id     BIGINT       NOT NULL,
    tenant_id      BIGINT       NOT NULL DEFAULT 1,
    data_vistoria  DATE,
    status1        VARCHAR(255),
    em_rota        BOOLEAN,
    sigla          VARCHAR(255),
    endereco       VARCHAR(255),
    cidade         VARCHAR(255),
    observacoes    TEXT
);

CREATE TABLE vistoria_visitas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT NOT NULL DEFAULT 1,
    vistoria_id  BIGINT NOT NULL REFERENCES vistorias (id),
    data_visita  DATE
);
